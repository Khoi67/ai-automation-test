import axios from 'axios';
import dotenv from 'dotenv';
import path from 'path';

dotenv.config({ path: path.resolve(process.cwd(), '.env') });

const API_BASE_URL = process.env.API_BASE_URL || 'https://elearningnew.cybersoft.edu.vn';
const TOKEN_CYBERSOFT = process.env.TOKEN_CYBERSOFT;
const MA_NHOM = process.env.MA_NHOM || 'GP01';
const TEST_USERNAME = process.env.TEST_USERNAME;
const TEST_PASSWORD = process.env.TEST_PASSWORD;

/**
 * Nightly Garbage Collection (GC) Script for Test Data.
 * Scans and purges dynamic test accounts matching 'auto_' or 'user_' prefixes.
 */
async function cleanupStaleTestData() {
  console.log('🧹 [STAGING TEST DATA GC] Starting cleanup process...');

  if (!TOKEN_CYBERSOFT) {
    console.error('❌ TOKEN_CYBERSOFT is missing from environment variables.');
    process.exit(1);
  }

  const baseHeaders = {
    TokenCybersoft: TOKEN_CYBERSOFT.trim(),
  };

  try {
    // 0. Authenticate to get Bearer AccessToken
    let bearerToken = '';
    if (TEST_USERNAME && TEST_PASSWORD) {
      try {
        const loginRes = await axios.post(
          `${API_BASE_URL}/api/QuanLyNguoiDung/DangNhap`,
          {
            taiKhoan: TEST_USERNAME,
            matKhau: TEST_PASSWORD,
          },
          { headers: baseHeaders },
        );
        bearerToken = loginRes.data?.accessToken || '';
        console.log('🔑 Authenticated successfully with test admin account.');
      } catch (authErr) {
        console.warn('⚠️ Could not obtain Bearer token, proceeding with base headers only.');
      }
    }

    const authHeaders = {
      ...baseHeaders,
      ...(bearerToken ? { Authorization: `Bearer ${bearerToken}` } : {}),
    };

    // 1. Fetch user list
    console.log(`📡 Fetching users for group: ${MA_NHOM}...`);
    const res = await axios.get(`${API_BASE_URL}/api/QuanLyNguoiDung/LayDanhSachNguoiDung`, {
      params: { MaNhom: MA_NHOM },
      headers: baseHeaders,
    });

    const users = res.data;
    if (!Array.isArray(users)) {
      console.log('⚠️ Unexpected response format. Aborting cleanup.');
      return;
    }

    // 2. Filter stale test users (do not delete static test account)
    const staleUsers = users.filter((u) => {
      const username = u.taiKhoan || '';
      const isAuto = username.startsWith('auto_') || username.startsWith('user_');
      const isNotStatic = username !== TEST_USERNAME;
      return isAuto && isNotStatic;
    });

    console.log(`🔍 Found ${staleUsers.length} stale test accounts generated by tests.`);

    if (staleUsers.length === 0) {
      console.log('✅ Database is clean. No stale test accounts to delete.');
      return;
    }

    // 3. Purge accounts (limited batch of 20 per run to prevent overloading)
    const BATCH_LIMIT = 20;
    const targets = staleUsers.slice(0, BATCH_LIMIT);
    let deletedCount = 0;

    for (const target of targets) {
      try {
        await axios.delete(`${API_BASE_URL}/api/QuanLyNguoiDung/XoaNguoiDung`, {
          params: { TaiKhoan: target.taiKhoan },
          headers: authHeaders,
        });
        deletedCount++;
        console.log(`  🗑️ Deleted stale account: ${target.taiKhoan}`);
      } catch (err) {
        const msg = err.response?.data?.content || err.response?.data || err.message;
        console.log(`  ⚠️ Skipped ${target.taiKhoan}: ${msg}`);
      }
    }

    console.log(`\n🎉 [GC COMPLETED] Successfully cleaned ${deletedCount}/${targets.length} test accounts.`);
  } catch (error) {
    console.error('❌ GC process encountered an error:', error.message);
  }
}

cleanupStaleTestData();
